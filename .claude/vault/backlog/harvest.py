def _safe_artifact_path(run_dir, relative):
    if not isinstance(relative, str) or not relative or os.path.isabs(relative):
        raise ValueError("완료 표식의 산출물 경로가 상대 경로가 아니다")
    normalized = os.path.normpath(relative)
    if normalized != relative or normalized == ".." or normalized.startswith(f"..{os.sep}"):
        raise ValueError("완료 표식의 산출물 경로가 실행 디렉터리 밖이다")
    path = os.path.abspath(os.path.join(run_dir, normalized))
    root = os.path.abspath(run_dir)
    if path != root and not path.startswith(root + os.sep):
        raise ValueError("완료 표식의 산출물 경로가 실행 디렉터리 밖이다")
    return path


def _artifact_paths(run_dir, index_data):
    paths = {"index.json", "rejections.md", ".stamp-candidate"}
    sessions = index_data.get("sessions")
    if not isinstance(sessions, list):
        raise ValueError("index.json의 sessions가 목록이 아니다")
    for session in sessions:
        if not isinstance(session, dict):
            raise ValueError("index.json의 session 항목이 객체가 아니다")
        relative = session.get("digest")
        _safe_artifact_path(run_dir, relative)
        paths.add(relative)
    return sorted(paths)


def _artifact_hashes(run_dir, index_data):
    hashes = {}
    for relative in _artifact_paths(run_dir, index_data):
        path = _safe_artifact_path(run_dir, relative)
        if not os.path.isfile(path):
            raise ValueError(f"산출물이 없다: {relative}")
        hashes[relative] = _sha256(path)
    return hashes


def _read_json_file(path, label):
    try:
        with open(path, encoding="utf-8") as fh:
            value = json.load(fh)
    except (OSError, ValueError) as exc:
        raise ValueError(f"{label}이(가) 올바른 JSON이 아니다") from exc
    if not isinstance(value, dict):
        raise ValueError(f"{label}이(가) 객체가 아니다")
    return value


def _read_candidate(path, now):
    try:
        with open(path, encoding="utf-8") as fh:
            lines = fh.read().splitlines()
    except OSError as exc:
        raise ValueError("도장 후보를 읽을 수 없다") from exc
    epoch = read_stamp(path, now=now)
    metadata_line = next(
        (line for line in lines[1:] if line.startswith("# harvest-metadata: ")),
        None,
    )
    if metadata_line is None:
        raise ValueError("도장 후보에 실행 메타데이터가 없다")
    try:
        metadata = json.loads(metadata_line[len("# harvest-metadata: "):])
    except ValueError as exc:
        raise ValueError("도장 후보 메타데이터가 올바른 JSON이 아니다") from exc
    if not isinstance(metadata, dict):
        raise ValueError("도장 후보 메타데이터가 객체가 아니다")
    return epoch, metadata


def _output_root(project, explicit_out, now):
    return explicit_out or os.path.join(
        project,
        ".claude/vault/backlog/sweep",
        dt.datetime.fromtimestamp(now, UTC).strftime("%Y-%m-%d"),
    )


def _run_dir(root, run_id):
    return os.path.join(root, "runs", run_id)


def _locate_run_dir(project, explicit_out, run_id, now):
    if explicit_out:
        return _run_dir(explicit_out, run_id)
    sweep_root = os.path.join(project, ".claude/vault/backlog/sweep")
    matches = glob.glob(os.path.join(sweep_root, "*", "runs", run_id))
    matches = [p for p in matches if os.path.isdir(p)]
    if len(matches) == 1:
        return matches[0]
    return _run_dir(_output_root(project, None, now), run_id)


def _existing_index(project, explicit_out, run_id, now):
    run_dir = _locate_run_dir(project, explicit_out, run_id, now)
    try:
        data = _read_json_file(os.path.join(run_dir, "index.json"), "index.json")
    except (OSError, ValueError):
        return None
    if data.get("run_id") != run_id or data.get("source") != project:
        return None
    return data


def _resume_now(project, explicit_out, run_id, requested_now):
    """같은 run-id를 재실행하면 최초 실행의 기준 시각을 유지한다."""
    data = _existing_index(project, explicit_out, run_id, requested_now)
    stored = data.get("now_epoch") if data else None
    if isinstance(stored, (int, float)) and math.isfinite(stored) and stored >= 0:
        return float(stored)
    return requested_now


def _identities_from_index(index_data):
    identities = []
    for session in index_data.get("sessions", []):
        if not isinstance(session, dict):
            raise ValueError("index.json의 session 항목이 객체가 아니다")
        source = session.get("source")
        session_id = session.get("session_id")
        if not isinstance(source, str) or not isinstance(session_id, str):
            raise ValueError("index.json에 source/session_id가 없다")
        identities.append({
            "source": source,
            "session_id": session_id,
            "session_path": session.get("session_path", ""),
        })
    return identities


def _validate_completed_run(run_dir, run_id, project, now):
    marker_path = os.path.join(run_dir, ".run-complete.json")
    if not os.path.isfile(marker_path):
        raise ValueError("완료 표식이 없다 — committable=false")
    marker = _read_json_file(marker_path, "완료 표식")
    if marker.get("run_id") != run_id:
        raise ValueError("완료 표식의 run_id가 요청과 다르다")
    if marker.get("source") != project:
        raise ValueError("완료 표식의 source가 현재 project와 다르다")
    if marker.get("committable") is not True:
        raise ValueError("완료 표식이 committable=true가 아니다")

    index = _read_json_file(os.path.join(run_dir, "index.json"), "index.json")
    if index.get("run_id") != run_id or index.get("source") != project:
        raise ValueError("index.json의 run/source 식별자가 맞지 않는다")
    identities = _identities_from_index(index)
    if marker.get("sessions") != identities:
        raise ValueError("완료 표식의 session 식별자가 맞지 않는다")

    candidate_path = os.path.join(run_dir, ".stamp-candidate")
    epoch, candidate = _read_candidate(candidate_path, now)
    if candidate.get("run_id") != run_id or candidate.get("source") != project:
        raise ValueError("도장 후보의 run/source 식별자가 맞지 않는다")
    if candidate.get("status") != "ready":
        raise ValueError("도장 후보가 ready 상태가 아니다")
    if candidate.get("sessions") != identities:
        raise ValueError("도장 후보의 session 식별자가 맞지 않는다")
    if candidate.get("candidate_epoch") != epoch:
        raise ValueError("도장 후보의 epoch 메타데이터가 첫 숫자와 다르다")

    expected = marker.get("artifacts")
    if not isinstance(expected, dict):
        raise ValueError("완료 표식에 산출물 hash가 없다")
    if marker.get("hashes") != expected:
        raise ValueError("완료 표식의 hash 필드가 서로 다르다")
    actual = _artifact_hashes(run_dir, index)
    if expected != actual:
        raise ValueError("산출물 hash가 완료 표식과 다르다 — committable=false")
    return epoch


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", default=os.getcwd())
    ap.add_argument("--since-hours", type=float, default=24)
    ap.add_argument("--exclude-recent-min", type=float, default=60)
    ap.add_argument("--out", default=None, help="기본: .claude/vault/backlog/sweep/<오늘>")
    ap.add_argument("--stamp-path", default=None,
                    help="성공 도장 경로. 기본: <project>/.claude/vault/backlog/sweep/.last-success")
    ap.add_argument("--now", default=None,
                    help="기준 시각 ISO 8601 (Z 또는 +00:00 필수, 드라이런 시뮬레이션용)")
    ap.add_argument("--run-id", default=None,
                    help="실행 식별자. 재개·commit-success 시 같은 값을 사용한다")
    ap.add_argument("--dry-run", action="store_true", help="표만 출력, 파일 안 씀")
    ap.add_argument("--commit-success", action="store_true",
                    help="완료된 run-id의 도장 후보를 실제 성공 도장으로 확정한다")
    a = ap.parse_args()

    try:
        now = parse_now(a.now)
    except ValueError as exc:
        print(f"✗ 기준 시각 오류: {exc}")
        return 2

    project = _project_identity(a.project)
    existing_index = None
    if not a.commit_success and a.run_id and not a.now:
        existing_index = _existing_index(project, a.out, a.run_id, now)
        now = _resume_now(project, a.out, a.run_id, now)
    stamp = a.stamp_path or os.path.join(
        project, ".claude/vault/backlog/sweep", ".last-success"
    )

    if a.commit_success:
        if a.dry_run:
            print("✗ --dry-run과 --commit-success를 함께 쓸 수 없다")
            return 2
        if not a.run_id:
            print("✗ --commit-success에는 --run-id가 필요하다")
            return 2
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,127}", a.run_id):
            print("✗ run-id 형식이 올바르지 않다")
            return 2
        run_dir = _locate_run_dir(project, a.out, a.run_id, now)
        try:
            epoch = _validate_completed_run(run_dir, a.run_id, project, now)
        except (OSError, ValueError) as exc:
            print(f"✗ 완료된 수확이 아니다: {exc}")
            return 1
        write_stamp(stamp, epoch)
        print(f"✓ 성공 도장 확정 {dt.datetime.fromtimestamp(epoch, UTC):%Y-%m-%dT%H:%M:%SZ} → {stamp}")
        return 0

    if a.run_id and not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,127}", a.run_id):
        print("✗ run-id 형식이 올바르지 않다")
        return 2
    run_id = a.run_id or _new_run_id(now)

    # Failsafe — 창을 "마지막 성공 이후"로 늘린다.
    # 고정 24시간이면 sweep 단계가 하루라도 못 뜬 날(맥북이 잠겼거나 실행이 죽었거나)
    # 그 사이 세션이 영영 안 걸린다. 창이 다음 날 이미 지나가 버리기 때문.
    # 마지막 성공 시각을 남겨두고 그 이후 전부를 훑으면 빠뜨림이 사라진다.
    since_h = a.since_hours
    exclude_recent_min = a.exclude_recent_min
    if existing_index is not None:
        stored_since = existing_index.get("since_hours")
        if isinstance(stored_since, (int, float)) and math.isfinite(stored_since) and stored_since >= 0:
            since_h = float(stored_since)
        stored_exclude = existing_index.get("exclude_recent_min")
        if (isinstance(stored_exclude, (int, float))
                and math.isfinite(stored_exclude) and stored_exclude >= 0):
            exclude_recent_min = float(stored_exclude)
    if os.path.exists(stamp):
        try:
            last = read_stamp(stamp, now=now)
            gap_h = (now - last) / 3600
            if gap_h > since_h:
                since_h = min(gap_h + 1, 24 * 14)   # 상한 2주 — 그 이상은 사람이 볼 일
                print(f"⚠ 마지막 성공이 {gap_h:.1f}시간 전 — 창을 {since_h:.1f}시간으로 넓힘 (건너뛴 날 복구)")
        except (OSError, ValueError) as exc:
            print(f"✗ 마지막 성공 시각을 읽을 수 없다: {exc}")
            return 2

    # 건너뛰기 경계 — discover() 안의 것과 같은 값. 도장 후보로 쓴다(맨 아래 주석 참조).
    cutoff = now - exclude_recent_min * 60
    sessions = discover(project, since_h, exclude_recent_min, now)
    targets = [s for s in sessions if s["verdict"] == "TARGET"]

    print(f"기준시각 {dt.datetime.fromtimestamp(now, UTC):%Y-%m-%dT%H:%MZ} · "
          f"창 {since_h:g}h · 최근 {exclude_recent_min:g}분 제외")
    print(f"{'store':7} {'sid':10} {'수정':12} {'크기':>8}  판정")
    for s in sessions:
        print(f"{s['store']:7} {short_id(s['sid']):10} "
              f"{dt.datetime.fromtimestamp(s['mtime'], UTC):%m-%dT%H:%MZ}  "
              f"{s['size_kb']:6d}KB  {s['verdict']}")
    by_store = {}
    for s in targets:
        by_store[s["store"]] = by_store.get(s["store"], 0) + 1
    print(f"\n대상 {len(targets)}개 / 스캔 {len(sessions)}개   {by_store}")

    if a.dry_run:
        print("\n(--dry-run: 파일 안 씀)")
        return 0

    out = _output_root(project, a.out, now)
    date = dt.datetime.fromtimestamp(now, UTC).strftime("%Y-%m-%d")
    run_dir = _run_dir(out, run_id)
    digest_dir = os.path.join(run_dir, "digest")
    os.makedirs(digest_dir, exist_ok=True)
    marker_path = os.path.join(run_dir, ".run-complete.json")
    try:
        os.unlink(marker_path)
    except FileNotFoundError:
        pass
    index, rej_all = [], []
    for s in targets:
        session_metadata = {
            "run_id": run_id,
            "source": s["store"],
            "session_id": s["sid"],
            "session_path": s["path"],
        }
        body = digest(s, session_metadata)
        name = f"{s['store']}-{short_id(s['sid'])}.md"
        digest_path = os.path.join(digest_dir, name)
        _atomic_write(digest_path, body)
        rj = rejections(s)
        rej_all.append((s, rj))
        index.append({
            "run_id": run_id,
            "source": s["store"],
            "session_id": s["sid"],
            "session_path": s["path"],
            "store": s["store"], "sid": s["sid"], "digest": f"digest/{name}",
            "mtime": dt.datetime.fromtimestamp(s["mtime"], UTC).isoformat(timespec="minutes"),
            "size_kb": s["size_kb"], "digest_bytes": len(body.encode()),
            "digest_sha256": _sha256(digest_path),
            "oversized": len(body.encode()) > DIGEST_CAP,
            "rejections": len(rj),
            "first_user": s.get("first_user", ""),
        })

    # 기각 순간 모음 — 후보만 긁은 것이라 진짜 기각인지는 LLM이 판정한다
    identities = [_session_identity(s) for s in targets]
    rejection_metadata = {
        "run_id": run_id,
        "source": project,
        "sessions": identities,
    }
    lines = [f"<!-- harvest-metadata: {_json_text(rejection_metadata)} -->", "",
             "# 기각 순간 후보 — 사람이 제안을 되돌린 자리", "",
             "> 어휘로 넓게 긁은 **후보**다(재현율 우선). 진짜 기각인지, 그 안에 담긴 판단 기준이",
             "> 무엇인지는 읽는 쪽이 판정한다. 동의는 정보가 없고 기각에 기준이 압축돼 있다는 전제.", ""]
    for s, rj in rej_all:
        if not rj:
            continue
        lines.append(f"\n## {s['store']}:{short_id(s['sid'])}  ({len(rj)}건)"
                     f" · source={s['store']} · session_id={s['sid']}")
        for i, r in enumerate(rj, 1):
            lines.append(f"\n**{i}. 직전 제안** — {r['proposal']}\n\n**→ 사람의 반응** — {r['rejection']}")
    rejections_text = "\n".join(lines) + "\n"
    _atomic_write(os.path.join(run_dir, "rejections.md"), rejections_text)

    index_data = {
        "run_id": run_id,
        "source": project,
        "generated_for": date,
        "generated_at": dt.datetime.fromtimestamp(now, UTC).isoformat(timespec="seconds"),
        "now_epoch": now,
        "project": project,
        "since_hours": since_h,
        "exclude_recent_min": exclude_recent_min,
        "scanned": len(sessions),
        "targets": len(targets),
        "sessions": index,
    }
    _atomic_write(
        os.path.join(run_dir, "index.json"),
        json.dumps(index_data, ensure_ascii=False, indent=2) + "\n",
    )
    over = sum(1 for i in index if i["oversized"])
    nrej = sum(i["rejections"] for i in index)
    print(f"\nrun_id {run_id}")
    print(f"다이제스트 {len(index)}개 → {digest_dir}/   (50KB 초과 {over}개 = 서브에이전트 위임 대상)")
    print(f"기각 순간 후보 {nrej}건 → {run_dir}/rejections.md")

    # 성공 도장은 여기서 찍지 않는다.
    #
    # 옛 동작: 수확이 끝나는 즉시 도장에 `now`(수확 시작 시각)를 찍었다. 두 가지가 고장나 있었다.
    #   ① 수확만 끝나고 노트·티켓·리포트가 하나도 없는 시점인데 "성공"으로 세어졌다.
    #      그래서 뒤 단계에서 죽으면 그 창의 대화가 통째로 사라졌다.
    #   ② 도장이 `now` 였는데 최근 N분은 "작업 중일 수 있다"고 건너뛴다. 즉 건너뛴 구간
    #      [now-N분, now] 는 다음 밤 창(= now 부터)에 안 들어간다. 매일 N분짜리 사각지대가
    #      생기고, 창을 넓히는 안전장치는 간격이 24시간을 못 넘어 영영 안 켜진다.
    #      2026-08-15 실사고 — 진짜 대화 5편(31MB)이 이 구멍에 빠질 뻔했다.
    #
    # 새 동작: 여기서는 **후보 시각만** 적어두고, 밤 루프가 리포트까지 다 낸 뒤
    # `--commit-success` 로 실제 도장을 찍는다. 후보 값은 `now` 가 아니라 **건너뛰기 경계**라,
    # 다음 밤 창이 이번에 건너뛴 지점에서 정확히 이어진다.
    candidate_metadata = {
        "run_id": run_id,
        "source": project,
        "sessions": identities,
        "candidate_epoch": cutoff,
        "status": "ready",
    }
    candidate_text = (
        f"{cutoff}  # {dt.datetime.fromtimestamp(cutoff, UTC):%Y-%m-%dT%H:%M:%SZ} "
        "= 이번 수확의 건너뛰기 경계. 완료 표식 검증 뒤 --commit-success 로 확정한다\n"
        f"# harvest-metadata: {_json_text(candidate_metadata)}\n"
    )
    _atomic_write(os.path.join(run_dir, ".stamp-candidate"), candidate_text)

    artifacts = _artifact_hashes(run_dir, index_data)
    marker = {
        "run_id": run_id,
        "source": project,
        "sessions": identities,
        "committable": True,
        "completed_at": dt.datetime.fromtimestamp(now, UTC).isoformat(timespec="seconds"),
        "artifacts": artifacts,
        "hashes": artifacts,
    }
    _atomic_write(marker_path, json.dumps(marker, ensure_ascii=False, indent=2) + "\n")
    print(f"\n도장 후보 {dt.datetime.fromtimestamp(cutoff, UTC):%Y-%m-%dT%H:%M:%SZ} → "
          f"{run_dir}/.stamp-candidate")
    print(f"완료 표식 {run_dir}/.run-complete.json (committable=true)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
