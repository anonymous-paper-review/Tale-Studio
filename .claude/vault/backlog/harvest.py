"""세션 수확기 — `_NIGHT.md` §4.1 수확 단계의 결정론 부분.

여러 저장소(Claude Code · gjc)에서 지정 프로젝트의 최근 세션을 찾아,
컨텍스트 위생 규칙에 맞는 다이제스트 파일로 떨군다.

왜 스크립트인가: 새벽 1:30 에이전트는 맥락 제로다. 저장소 위치·스키마·
오탐 함정을 프롬프트로 설명하면 매번 다르게 해석한다. 판별은 여기서 얼리고,
에이전트는 다이제스트만 읽는다.

  python3 .claude/vault/backlog/harvest.py --dry-run     # 표만 출력, 쓰기 없음
  python3 .claude/vault/backlog/harvest.py               # 다이제스트 생성

일반 실행은 `<out>/runs/<run_id>/`에만 산출물을 쓴다. `run_id`는
`--run-id`로 재개할 수 있고, 생략하면 `run-<UTC timestamp>-<uuid>`로 만든다.
`index.json`, `rejections.md`, 다이제스트의 메타데이터, `.stamp-candidate`에는
실행(run), 원천(source), 세션(session) 식별자가 함께 들어간다. 마지막에
`.run-complete.json`을 원자적으로 교체한 경우에만 실행을 완료한 것으로 본다.
완료 표식의 해시·식별자가 맞을 때만 `--commit-success --run-id <id>`가
성공 도장을 확정한다. 표식이 없거나 산출물이 바뀌면 `committable=false`다.
"""
