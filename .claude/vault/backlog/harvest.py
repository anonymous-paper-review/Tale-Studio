HOME = os.path.expanduser("~")
UTC = dt.timezone.utc

# 실제 Skill 호출만 인정한다. 느슨한 부분일치(`command-name>` 안에 warp/wrap)를
# 쓰면 밤 계약 본문을 읽은 세션이 전부 "warp 완료"로 오탐된다 — 이 파일과
# 수확 단계를 논의한 세션일수록 수확에서 사라지는 자기참조 함정.
# 실측 형태: "name":"Skill","input":{"skill":"wrap"}   (2026-08-11 warp로 개명)
WARP_CALL = re.compile(r'"name"\s*:\s*"Skill"\s*,\s*"input"\s*:\s*\{\s*"skill"\s*:\s*"(warp|wrap)"')

# 러너/sweep 단계 자신의 세션은 "첫 발화"로만 판정한다. 본문 어디든 파일명이
# 있으면 스킵하는 규칙은 위와 같은 오탐을 만든다.
BOOT_PHRASE = re.compile(r'_(RUNNER|SWEEP)\.md\s*(를|을)?\s*읽고')

ASSISTANT_CAP = 500   # assistant 텍스트 절단 (원출력 대량 인용 금지)
DIGEST_CAP = 50_000   # 초과 시 서브에이전트 위임 대상으로 표시

# user 롤로 도착하지만 사람이 친 게 아닌 것들 — 스킬 본문·훅 주입·압축 요약.
# 실측(2026-08-11, 17세션/157발화): 3000자 초과 10건이 user 텍스트 부피의 95%였고
# 그 10건이 전부 주입물이었다. 사람 발화는 전원 3000자 미만.
# 주입원을 일일이 열거하면 훅이 늘 때마다 깨지므로 길이 상한을 1차 방어선으로 쓴다.
USER_CAP = 3000
INJECTED_PREFIXES = (
    "Base directory for this skill:",
    "Caveat: The messages below were generated by the user while running local commands",
    "This session is being continued from a previous conversation",
)

# 기각 순간 — 대화에서 재사용 가치가 있는 유일한 고신호 구간.
#
# 원본 트랜스크립트 전체는 노이즈다("무엇을 했는가"만 남고 "왜 그걸 골랐는가"는 안 남는다).
# 재사용되는 건 **사람이 제안을 되돌린 순간**이다 — 동의("ㅇㅇ 진행")엔 정보가 거의 없고,
# 기각·되물음에 판단 기준이 압축돼 있다. 원자료 위에 얹는 정제된 중간 표현.
#
# 여기서는 **후보만 넓게 긁는다**(재현율 우선). 진짜 기각인지 판정은 LLM이 한다 —
# 싸게 전수 열거하고 비싸게 판정하는 2층 구조.
REJECT_MARKERS = re.compile(
    r"아닌데|아니라|아니고|아니야|아니에|^아니|ㄴㄴ|말고|빼고|"
    r"이해\s*못|이해못|모르겠|뭔\s*말|무슨\s*말|뭔소리|어렵|"
    r"잘못|틀렸|틀린|이상한|이상함|구림|구린|별로|아쉬|부족|"
    r"다시|재작성|재구성|고쳐|바꿔|"
    r"맞음\?|맞나|맞아\?|이게\s*맞|왜\s|왜\?|"
    r"미안한데|솔직히|근데\s",
    re.M,
)
# 승인으로 시작하는 발화는 기각이 아니다. 실측(2026-08-11)에서 "좋은듯?", "오오오 내가원한게
# 딱 이런표임" 같은 명백한 동의가 뒤에 붙은 "근데/?" 때문에 기각으로 잡혔다.
APPROVE_HEAD = re.compile(r"^\s*(좋|오오|굿|ㅇㅇ|넵|넵넵|오케|오키|ok|OK|완벽|훌륭|나이스|짱)")


def _iter_json(path):
    with open(path, encoding="utf-8", errors="ignore") as fh:
        for line in fh:
            try:
                yield json.loads(line)
            except Exception:
                continue


def _texts(content):
    """content 배열에서 순수 text 블록만. thinking/tool_use/tool_result 제외."""
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return ""
    return "".join(
        b.get("text", "") for b in content
        if isinstance(b, dict) and b.get("type") == "text"
    )


def _turns_claude(path):
    """Claude Code 스키마: {"type":"user"|"assistant","message":{"content":[...]}}"""
    for o in _iter_json(path):
        t = o.get("type")
        if t not in ("user", "assistant"):
            continue
        msg = o.get("message")
        if not isinstance(msg, dict):
            continue
        txt = _texts(msg.get("content"))
        if txt.strip():
            yield t, txt.strip()


def _turns_gjc(path):
    """gjc 스키마: {"type":"message","message":{"role":"user"|"assistant"|"toolResult"}}"""
    for o in _iter_json(path):
        msg = o.get("message")
        if not isinstance(msg, dict):
            continue
        role = msg.get("role")
        if role not in ("user", "assistant"):   # toolResult 제외
            continue
        txt = _texts(msg.get("content"))
        if txt.strip():
            yield role, txt.strip()


def short_id(sid):
    """세션 식별자 8자. gjc 파일명은 `<ISO타임스탬프>_<uuid>` 라서 앞 8자를 쓰면
    같은 날 세션이 전부 `2026-08-` 로 충돌한다 — uuid 쪽을 쓴다."""
    return (sid.rsplit("_", 1)[-1] if "_" in sid else sid)[:8]


def _gjc_cwd(path, limit=300):
    for i, o in enumerate(_iter_json(path)):
        if i > limit:
            break
        if o.get("cwd"):
            return o["cwd"]
    return None


def parse_now(value):
    """명시적 기준 시각을 UTC epoch로 바꾼다. 시간대 없는 값은 거부한다."""
    if value is None:
        return dt.datetime.now(UTC).timestamp()
    normalized = value.replace("Z", "+00:00")
    parsed = dt.datetime.fromisoformat(normalized)
    if parsed.tzinfo is None:
        raise ValueError("기준 시각에 시간대가 없다. Z 또는 +00:00을 붙여라")
    return parsed.astimezone(UTC).timestamp()


def _atomic_write(path, text):
    """같은 디렉터리에서 교체해 부분 파일을 노출하지 않는다."""
    parent = os.path.dirname(path) or "."
    os.makedirs(parent, exist_ok=True)
    temporary = f"{path}.tmp-{os.getpid()}-{uuid.uuid4().hex}"
    try:
        with open(temporary, "w", encoding="utf-8") as fh:
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(temporary, path)
    finally:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass


def _sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _json_text(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def read_stamp(path, now=None):
    """성공 도장을 읽는다.

    도장은 유한한 0 이상 숫자 epoch만 허용한다. 날짜 문자열이나 손상된
    숫자를 조용히 살리면 세션 창이 줄어들어 누락되므로 호출자가 복구해야
    하는 오류로 올린다.
    """
    with open(path, encoding="utf-8") as fh:
        raw = fh.read().strip()
    if not raw:
        raise ValueError("도장 파일이 비어 있다")
    head = raw.split()[0]
    try:
        epoch = float(head)
    except ValueError as exc:
        raise ValueError("도장은 숫자 epoch여야 한다") from exc
    if not math.isfinite(epoch) or epoch < 0:
        raise ValueError("도장 epoch가 유한한 0 이상 숫자가 아니다")
    if now is not None and epoch > now:
        raise ValueError("도장이 기준 시각보다 미래다")
    return epoch


def write_stamp(path, epoch):
    """도장을 쓴다. 숫자 뒤에 사람이 읽는 날짜를 주석으로 붙여
    '이게 무슨 파일인지 몰라서 날짜 글자로 덮어쓰는' 사고를 막는다."""
    when = dt.datetime.fromtimestamp(epoch, UTC)
    _atomic_write(
        path,
        f"{epoch}  # {when:%Y-%m-%dT%H:%M:%SZ} — 첫 숫자만 읽는다. "
        f"손으로 고칠 때 숫자를 날짜 글자로 바꾸지 마라(2026-08-14 실사고)\n",
    )


def discover(project, since_h, exclude_recent_min, now):
    """저장소별로 후보 세션을 모은다. 반환: dict 리스트."""
    win_start = now - since_h * 3600
    cutoff = now - exclude_recent_min * 60
    out = []

    # --- Claude Code: 디렉토리명이 인코딩된 프로젝트 경로 ---
    enc = project.replace("/", "-")
    for p in glob.glob(f"{HOME}/.claude/projects/{enc}/*.jsonl"):
        out.append({"store": "claude", "path": p, "turns": _turns_claude})

    # --- gjc: 디렉토리명이 해시다. 프로젝트는 파일 안 cwd 로만 판별 ---
    #   (읽기 좋은 sessions/-projects-<name>/ 은 구형 경로 — 오늘 것은 여기 안 들어온다)
    for p in glob.glob(f"{HOME}/.gjc/agent/sessions/*/*.jsonl"):
        if os.path.getmtime(p) < win_start:
            continue          # cwd 파싱 전에 싸게 거른다
        if _gjc_cwd(p) == project:
            out.append({"store": "gjc", "path": p, "turns": _turns_gjc})

    sessions = []
    for c in out:
        p = c["path"]
        m = os.path.getmtime(p)
        rec = {
            "store": c["store"],
            "sid": os.path.basename(p)[:-6],
            "path": p,
            "mtime": m,
            "size_kb": os.path.getsize(p) // 1024,
            "_turns": c["turns"],
        }
        if not (win_start <= m):
            rec["verdict"] = "skip:창밖"
        elif m > cutoff:
            rec["verdict"] = "skip:작업중"
        else:
            raw = open(p, encoding="utf-8", errors="ignore").read()
            first_user = next((t for r, t in c["turns"](p) if r == "user" and not t.startswith("<")), "")
            rec["first_user"] = first_user[:200]
            if WARP_CALL.search(raw):
                rec["verdict"] = "skip:warp완료"
            elif BOOT_PHRASE.search(first_user):
                rec["verdict"] = "skip:러너/sweep 단계"
            else:
                rec["verdict"] = "TARGET"
        sessions.append(rec)

    sessions.sort(key=lambda r: -r["mtime"])
    return sessions


def digest(rec, metadata=None):
    """세션 1개 → 다이제스트 텍스트. user 전문 + assistant 500자 절단."""
    lines = []
    if metadata is not None:
        lines.extend([f"<!-- harvest-metadata: {_json_text(metadata)} -->", ""])
    lines.extend([
        f"# 세션 다이제스트 — {rec['store']}:{short_id(rec['sid'])}",
        "",
        f"- 저장소: `{rec['path']}`",
        f"- 최종 수정: {dt.datetime.fromtimestamp(rec['mtime'], UTC):%Y-%m-%dT%H:%MZ}  ({rec['size_kb']}KB)",
        "",
        "> user 발화는 전문, assistant는 500자 절단. thinking·tool_use·tool_result 제외.",
        "",
    ])
    for role, txt in rec["_turns"](rec["path"]):
        if role == "user":
            if txt.startswith("<"):        # system-reminder·cross-session-message 등
                continue
            if txt.startswith(INJECTED_PREFIXES):
                continue
            if len(txt) > USER_CAP:        # 붙여넣기 폭탄·미지의 주입원 방어
                txt = txt[:USER_CAP] + f" …(+{len(txt)-USER_CAP}자 절단)"
            lines.append(f"\n## USER\n{txt}")
        else:
            t = txt[:ASSISTANT_CAP]
            if len(txt) > ASSISTANT_CAP:
                t += f" …(+{len(txt)-ASSISTANT_CAP}자)"
            lines.append(f"\n### assistant\n{t}")
    return "\n".join(lines)


def rejections(rec):
    """(직전 제안, 사람의 기각) 쌍을 뽑는다.

    기각 발화만 떼어놓으면 "무엇을 기각했는지"가 사라지므로 반드시 쌍으로 남긴다 —
    재사용되는 최소 단위가 쌍이다."""
    out, prev = [], None
    for role, txt in rec["_turns"](rec["path"]):
        if role == "user":
            if txt.startswith("<") or txt.startswith(INJECTED_PREFIXES):
                continue
            if (len(txt) <= USER_CAP and REJECT_MARKERS.search(txt)
                    and not APPROVE_HEAD.match(txt)):
                out.append({"proposal": (prev or "")[:400], "rejection": txt[:800]})
        else:
            prev = txt
    return out


