/** 화면 정적 그리기는 가게의 처음 값(getInitialState)을 읽는다 — 지금 값과 처음 값을 함께 둔다. */
function seed<T extends object>(store: { setState: (s: Partial<T>) => void; getInitialState: () => T }, values: Partial<T>) {
  store.setState(values)
  Object.assign(store.getInitialState(), values)
}

function stubFetch(answer: (url: string, init?: RequestInit) => Response) {
  const calls: Array<{ call: string; body: unknown }> = []
  vi.stubGlobal('fetch', vi.fn(async (url: string, init?: RequestInit) => {
    calls.push({ call: `${init?.method ?? 'GET'} ${url}`, body: init?.body ? JSON.parse(String(init.body)) : null })
    if (url.startsWith('/api/artist/generation-status')) {
      return new Response(JSON.stringify({ failures: [], queuedMain: [], worldFailures: [], queuedWorld: [], imagesStarted: true }), { status: 200 })
    }
    return answer(url, init)
  }))
  return calls
}

describe('같이 정한 것', () => {
  beforeEach(() => {
    useProjectStore.setState({ projectId: 'p1' })
    useArtistStore.setState({ imagesStarted: false })
    mocks.toastError.mockClear()
  })
  afterEach(() => {
    useProjectStore.setState({ projectId: null })
    vi.unstubAllGlobals()
  })

  // 왜: O1 "콘티를 Artist 앞에" — 씬 · 샷이 산문 확정 뒤에 나뉘어, Artist 에 처음 오면 디자인은 끝났고 샷은 있고 그림은 없다. 그때 그림체와 [이미지 만들기]를 보인다(리드 2차).
  it('산문을 확정해 디자인과 씬 · 샷 나누기가 끝났는데 그림을 아직 그리지 않았으면 Artist 는 [이미지 만들기]를 기다리는 단계다', () => {
    expect(artistPhase({ ...ARRIVED, imagesStarted: false, anyImage: false, drawing: false })).toBe('ready')
    // 사람이 올린 그림(레퍼런스로 그대로 쓰는 그림 · Producer 카드 그림)이 있어도 그림 작업이 없었으면 아직 [이미지 만들기] 전이다.
    expect(artistPhase({ ...ARRIVED, imagesStarted: false, anyImage: true, drawing: false })).toBe('ready')
  })

  // 왜: 리드 2차 "들어오자마자 저절로 그리지 않는다" — 지금은 카드 단계면 들어오자마자 빈 그림을 그렸다. [이미지 만들기]를 기다리는 단계에서는 그리지 않는다.
  it('[이미지 만들기]를 기다리는 단계에서는 Artist 에 들어와도 그림을 저절로 그리지 않는다', () => {
    expect(autoGenerateOnEnter({ phase: 'ready' })).toBe(false)
    expect(autoGenerateOnEnter({ phase: 'cards' })).toBe(true)
  })

  // 왜: O1 "Artist [만들기]는 그림만" — 씬 · 샷과 산문은 이미 나뉘었다. 그림 창구만 부르고 Writer 실행은 건드리지 않는다.
  it('[이미지 만들기]를 누르면 인물 · 배경 · 소품 그림만 그리고 씬 · 샷과 산문은 그대로다', async () => {
    const calls = stubFetch(() => new Response(JSON.stringify({ ok: true, style: null, characters: { submitted: 2 }, worlds: { submitted: 1 } }), { status: 200 }))
    expect(await useArtistStore.getState().makeImages('real')).toEqual({ ok: true, style: null })
    expect(calls[0]).toEqual({ call: 'POST /api/artist/make-images', body: { projectId: 'p1', styleAnchorKey: 'real' } })
    expect(calls.some(({ call }) => /\/api\/writer\//.test(call))).toBe(false)
    expect(useArtistStore.getState().imagesStarted).toBe(true)
  })

  // 왜: O6 "산문 확정 창에서 한 번 고르게 하고 artist에서 계속 변경할 수 있게" — [이미지 만들기] 창에서 고른 그림체를 서버가 저장하면 화면의 그림체도 그것으로 바뀐다.
  it('[이미지 만들기] 창에서 그림체를 바꾸면 그 그림체로 저장하고 그 그림체로 그림만 그린다', async () => {
    stubFetch(() => new Response(JSON.stringify({ ok: true, style: 'watercolor' }), { status: 200 }))
    expect(await useArtistStore.getState().makeImages('watercolor')).toEqual({ ok: true, style: 'watercolor' })
    const dialog = readFileSync('src/features/artist-room/style-make-dialog.tsx', 'utf8')
    const imagesBranch = dialog.slice(dialog.indexOf("if (mode === 'images')"))
    expect(imagesBranch).toMatch(/makeImages\(/)
    expect(imagesBranch).toMatch(/useProducerStore\.setState\(\{ styleAnchorKey: result\.style, customStyleAnchor: null \}\)/)
    // 산문을 확정한 뒤라 화면에서 그림체를 직접 저장하지 못한다(setStyleAnchor 는 막혀 있다) — 서버 창구가 저장한다.
    expect(imagesBranch.slice(0, imagesBranch.indexOf('return'))).not.toMatch(/setStyleAnchor/)
  })
})

describe('혼자 정한 것', () => {
  beforeEach(() => {
    mocks.jobs = []
    mocks.jobsError = null
    mocks.toastError.mockClear()
    useProjectStore.setState({ projectId: 'p1' })
    useArtistStore.setState({ imagesStarted: false })
  })
  afterEach(() => {
    useProjectStore.setState({ projectId: null })
    vi.unstubAllGlobals()
  })

  // 왜: [이미지 만들기]를 누른 뒤에는 그리는 중이거나 그림이 생겼다 — 지금처럼 카드 · 진행 · [완료하기]다. 그림이 다 실패해도 카드의 [다시 그리기]로 고친다.
  it('그림을 그리기 시작했거나 그리는 중이면 [이미지 만들기] 단계가 아니라 카드 단계다', () => {
    expect(artistPhase({ ...ARRIVED, imagesStarted: true, anyImage: false, drawing: false })).toBe('cards')
    expect(artistPhase({ ...ARRIVED, imagesStarted: false, anyImage: false, drawing: true })).toBe('cards')
  })

  // 왜: 그림 작업 기록을 읽기 전(새로고침 직후)에는 그림이 있으면 예전처럼 카드로 보고, 없으면 [이미지 만들기] 단계로 본다 — 만드는 중 화면이 잠깐 덮이지 않게.
  it('그림 상태를 읽기 전에는 그림이 있으면 카드, 없으면 [이미지 만들기] 단계로 본다', () => {
    expect(artistPhase({ ...ARRIVED, imagesStarted: null, anyImage: true, drawing: false })).toBe('cards')
    expect(artistPhase({ ...ARRIVED, imagesStarted: null, anyImage: false, drawing: false })).toBe('ready')
  })

  // 왜: 그림을 작업 기록 없이 옮겨 온 프로젝트(개발 → 운영 복사)나 올린 그림으로 다 채운 프로젝트는 [이미지 만들기]로 그릴 것이 없다 — [완료하기]로 간다.
  it('모든 카드에 그림이 이미 있으면 그릴 것이 없어 [이미지 만들기] 단계가 아니다', () => {
    expect(artistPhase({ ...ARRIVED, allDrawn: true, imagesStarted: false, anyImage: true, drawing: false })).toBe('cards')
  })

  // 왜: 정상 경로 고정 — 예전 흐름(샷이 아직 없음)과 [완료하기] 뒤는 지금 그대로다.
  it('샷이 아직 없거나 [완료하기]를 한 뒤에는 [이미지 만들기] 단계가 아니다', () => {
    expect(artistPhase({ ...ARRIVED, shotsExist: false, imagesStarted: false, anyImage: false, drawing: false })).toBe('cards')
    expect(artistPhase({ ...ARRIVED, artistCompleted: true, imagesStarted: false, anyImage: false, drawing: false })).toBe('done')
  })

  // 왜: 화면이 그림 상태(생성 상태 창구)를 읽기 전에 정하면, 올린 그림이 있는 [이미지 만들기] 전 프로젝트를 카드 단계로 잘못 보고 들어오자마자 그린다.
  it('씬 · 샷이 나뉜 프로젝트는 그림 상태를 읽은 뒤에야 들어올 때 저절로 그릴지 정한다', () => {
    expect(autoGenerateDecidable({ shotsExist: true, imageStateKnown: false })).toBe(false)
    expect(autoGenerateDecidable({ shotsExist: true, imageStateKnown: true })).toBe(true)
    // 예전 흐름(샷이 아직 없음)은 지금처럼 진행 상태만 읽고 정한다.
    expect(autoGenerateDecidable({ shotsExist: false, imageStateKnown: false })).toBe(true)
  })

  // 왜: [이미지 만들기]를 눌렀는지는 그림 작업이 한 번이라도 있었는지로 가린다(인물 시트 · 배경 · 소품 그림) — 사람이 올린 그림은 작업이 없어 [이미지 만들기] 전으로 남는다.
  it('인물 · 배경 · 소품 그림 작업이 하나라도 있으면 그림을 그리기 시작한 것으로 본다', async () => {
    mocks.jobs = [{ project_id: 'p1', kind: 'shot_rough_storyboard', status: 'completed' }]
    expect(await artistImagesStarted('p1')).toBe(false)
    mocks.jobs.push({ project_id: 'p1', kind: 'prop_image', status: 'failed' })
    expect(await artistImagesStarted('p1')).toBe(true)
    expect(await artistImagesStarted('p2')).toBe(false)
  })

  // 왜: 읽지 못하면 모른다(null) — 그때 화면은 그림이 있는지로만 가린다.
  it('그림 작업 기록을 읽지 못하면 모른다고 답한다', async () => {
    mocks.jobsError = { message: 'boom' }
    expect(await artistImagesStarted('p1')).toBeNull()
  })

  // 왜: 화면이 [이미지 만들기] 전인지 알 수 있게 생성 상태 창구가 함께 알려 준다.
  it('생성 상태 창구는 그림을 그리기 시작했는지를 함께 알려 준다', () => {
    const route = readFileSync('src/app/api/artist/generation-status/route.ts', 'utf8')
    expect(route).toMatch(/artistImagesStarted\(projectId\)/)
    expect(route).toMatch(/imagesStarted \}\)/)
  })

  // 왜: 다른 창에서 이미 [이미지 만들기]를 눌러 그리는 중이면 또 보내지 않고 그 그림을 기다린다(서버가 drafts_already_queued 로 막는다).
  it('[이미지 만들기]를 눌렀는데 이미 그리는 중이면 다시 그리지 않고 그 그림을 기다린다', async () => {
    stubFetch(() => new Response(JSON.stringify({ error: 'Draft image generation already queued', code: 'drafts_already_queued' }), { status: 409 }))
    expect(await useArtistStore.getState().makeImages('real')).toEqual({ ok: true, style: null })
    expect(useArtistStore.getState().imagesStarted).toBe(true)
    expect(mocks.toastError).not.toHaveBeenCalled()
  })

  // 왜: 그림을 그리기 시작한 뒤에는 그림체를 [재생성하기]로만 바꾼다(버전 기록이 남는 길) — 거절되면 까닭을 알리고 [이미지 만들기] 단계에 남는다.
  it('[이미지 만들기]가 거절되면 까닭을 알리고 그림을 그리기 시작한 것으로 치지 않는다', async () => {
    stubFetch(() => new Response(JSON.stringify({ error: 'Images were already started', code: 'images_started' }), { status: 409 }))
    expect(await useArtistStore.getState().makeImages('watercolor')).toEqual({ ok: false, style: null })
    expect(useArtistStore.getState().imagesStarted).toBe(false)
    expect(mocks.toastError).toHaveBeenCalledWith('The images have already been started. To change the style, use Regenerate everything.')
  })

  // 왜: [이미지 만들기] 전에 소품 하나를 [그리기]로 그리면 그림 작업이 생겨 카드 단계로 넘어가고, 이어 그리기가 나머지 그림을 다 그려 버린다 — 그림은 [이미지 만들기]로 시작한다.
  it('[이미지 만들기] 단계에서는 소품 카드의 [그리기]가 보이지 않는다', () => {
    const sword = { propId: 'sword', name: '칼', appearance: 'a sword', appearanceNative: '칼', imageUrl: null, sourceHash: null, origin: 'writer' as const }
    seed(useArtistStore, { propAssets: [sword], generatingProps: [], propFailures: {}, propContentRefusals: {} })
    expect(renderToStaticMarkup(createElement(PropPanel, { columns: 2, drawLocked: true }))).not.toContain('data-testid="artist-prop-draw"')
    expect(renderToStaticMarkup(createElement(PropPanel, { columns: 2 }))).toContain('data-testid="artist-prop-draw"')
    seed(useArtistStore, { propAssets: [] })
    expect(readFileSync('src/app/studio/artist/page.tsx', 'utf8')).toMatch(/<PropPanel[^>]*drawLocked=\{phase === 'ready'\}/)
  })

  // 왜: [이미지 만들기] 전에는 다시 그리거나 불러올 그림이 없다 — 그림체는 [이미지 만들기] 창에서 바꾼다.
  it('[이미지 만들기] 단계에서는 그림체 막대가 불러오기 · 재생성하기 대신 그림체는 이미지를 만들 때 바꾼다고 알린다', () => {
    const real = { key: 'real', label: '실사', medium: 'live_action', imageUrl: null, previewUrl: null, subtitle: null } satisfies StyleAnchor
    seed(useProducerStore, { styleAnchors: [real], styleAnchorKey: 'real', customStyleAnchor: null })
    seed(useArtistVersionStore, { versions: [], loaded: true, busy: null, regen: null, restoring: false, loadFailed: null })
    const before = renderToStaticMarkup(createElement(StyleVersionBar, { completed: false, drawing: false, beforeImages: true }))
    expect(before).toContain('data-testid="artist-style-before-images"')
    expect(before).not.toContain('data-testid="artist-regen-open"')
    expect(before).not.toContain('data-testid="artist-version-history-open"')
    expect(renderToStaticMarkup(createElement(StyleVersionBar, { completed: false, drawing: false }))).toContain('data-testid="artist-regen-open"')
  })

  // 왜: [이미지 만들기] 단계에는 완료할 그림이 없다 — [완료하기] 대신 [이미지 만들기]를 보이고, 그 창은 그림만 그린다.
  it('[이미지 만들기] 단계에서는 [완료하기] 대신 [이미지 만들기]를 보인다', () => {
    const page = readFileSync('src/app/studio/artist/page.tsx', 'utf8')
    expect(page).toMatch(/phase === 'ready' \? \(/)
    expect(page).toMatch(/data-testid="artist-make-images"/)
    expect(page).toMatch(/<StyleMakeDialog mode="images"/)
    expect(page).toMatch(/\{phase === 'ready' \? \(\s*\/\/[^\n]*\n\s*<StyleVersionBar [^\n]*beforeImages \/>/)
  })

  // 왜: 지금 규칙 — Artist 는 그림을 다 그린 뒤에만 러프를 미리 그린다(rough-storyboard-trigger). [이미지 만들기] 전은 그림이 하나도 없다.
  it('[이미지 만들기] 단계에서는 러프를 미리 그리지 않는다', () => {
    const page = readFileSync('src/app/studio/artist/page.tsx', 'utf8')
    expect(page).toMatch(/backgroundRoughReady\(\{[^}]*phase === 'ready'/)
  })
})
